// Regenerates src/generated/naics-2022.ts, the embedded 2022 NAICS reference
// targeting codes are checked against (LIF-1694).
//
// Source: US Census Bureau, 2022 NAICS "2-6 digit" codes file
//   https://www.census.gov/naics/2022NAICS/2-6%20digit_2022_Codes.xlsx
// Download it, then run:
//   node scripts/sync-naics-2022.mjs <path-to-2-6-digit_2022_Codes.xlsx>
// Add --check to compare against the committed file without writing.
//
// The workbook's first sheet lists "Seq. No., 2022 NAICS US Code, 2022 NAICS US
// Title". Ranged sectors (31-33, 44-45, 48-49) are written as each two-digit
// part because a search matches codes hierarchically by prefix.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { inflateRawSync } from "node:zlib";

const [source, flag] = process.argv.slice(2);
if (!source || (flag && flag !== "--check"))
  throw new Error("Usage: node scripts/sync-naics-2022.mjs <2-6 digit_2022_Codes.xlsx> [--check]");
const target = new URL("../src/generated/naics-2022.ts", import.meta.url);
const workbook = readFileSync(source);

// Minimal ZIP reader: the central directory names each entry and its offset.
function entries(zip) {
  let end = zip.length - 22;
  while (end >= 0 && zip.readUInt32LE(end) !== 0x06054b50) end -= 1;
  if (end < 0) throw new Error("Not an xlsx (ZIP) file.");
  const count = zip.readUInt16LE(end + 10);
  let offset = zip.readUInt32LE(end + 16);
  const files = new Map();
  for (let index = 0; index < count; index += 1) {
    if (zip.readUInt32LE(offset) !== 0x02014b50) throw new Error("Corrupt ZIP directory.");
    const method = zip.readUInt16LE(offset + 10);
    const size = zip.readUInt32LE(offset + 20);
    const nameLength = zip.readUInt16LE(offset + 28);
    const extraLength = zip.readUInt16LE(offset + 30);
    const commentLength = zip.readUInt16LE(offset + 32);
    const local = zip.readUInt32LE(offset + 42);
    const name = zip.toString("utf8", offset + 46, offset + 46 + nameLength);
    const dataStart = local + 30 + zip.readUInt16LE(local + 26) + zip.readUInt16LE(local + 28);
    const data = zip.subarray(dataStart, dataStart + size);
    files.set(name, () => (method === 0 ? data : inflateRawSync(data)).toString("utf8"));
    offset += 46 + nameLength + extraLength + commentLength;
  }
  return files;
}

const decode = (text) =>
  text.replace(/&(amp|lt|gt|quot|apos|#\d+);/g, (_, entity) =>
    ({ amp: "&", lt: "<", gt: ">", quot: '"', apos: "'" })[entity] ??
    String.fromCodePoint(Number(entity.slice(1))));
const files = entries(workbook);
const strings = [...(files.get("xl/sharedStrings.xml")?.() ?? "").matchAll(/<si>([\s\S]*?)<\/si>/g)].map(([, item]) =>
  decode([...item.matchAll(/<t[^>]*>([\s\S]*?)<\/t>/g)].map(([, text]) => text).join("")));
const sheet = files.get("xl/worksheets/sheet1.xml")?.();
if (!sheet) throw new Error("The workbook has no first sheet.");
const cell = (row, column) => {
  const match = row.match(new RegExp(`<c r="${column}\\d+"([^>]*?)(?:/>|>([\\s\\S]*?)</c>)`));
  if (!match || !match[2]) return "";
  const value = match[2].match(/<v>([\s\S]*?)<\/v>/)?.[1] ?? match[2].match(/<t[^>]*>([\s\S]*?)<\/t>/)?.[1] ?? "";
  return (/t="s"/.test(match[1]) ? strings[Number(value)] : decode(value)).trim();
};

const codes = new Map();
for (const [, row] of sheet.matchAll(/<row[^>]*>([\s\S]*?)<\/row>/g)) {
  const code = cell(row, "B");
  const title = cell(row, "C");
  if (!/^\d{2,6}(-\d{2})?$/.test(code)) continue;
  const [first, last] = code.split("-");
  for (let part = Number(first); part <= Number(last ?? first); part += 1) codes.set(String(part), title);
}
if (codes.size < 2000) throw new Error(`Expected about 2,100 codes, found ${codes.size}.`);
const sorted = [...codes].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const digest = createHash("sha256").update(workbook).digest("hex");
const content = `// Generated by scripts/sync-naics-2022.mjs from the US Census Bureau 2022 NAICS
// "2-6 digit" codes file (2-6 digit_2022_Codes.xlsx, SHA-256 ${digest}).
// Do not edit by hand: download the file again and rerun the script (LIF-1694).
// Ranged sectors 31-33, 44-45 and 48-49 are listed as their two-digit parts.
export const NAICS_2022: Readonly<Record<string, string>> = {
${sorted.map(([code, title]) => `  "${code}": ${JSON.stringify(title)},`).join("\n")}
};
`;
if (flag === "--check") {
  if (readFileSync(target, "utf8") !== content) {
    console.error("src/generated/naics-2022.ts differs from the workbook; rerun without --check.");
    process.exit(1);
  }
  console.log(`naics-2022.ts matches (${sorted.length} codes).`);
} else {
  writeFileSync(target, content);
  console.log(`Wrote ${sorted.length} codes to src/generated/naics-2022.ts.`);
}
