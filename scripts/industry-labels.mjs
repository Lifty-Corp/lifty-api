// Regenerates src/generated/industry-labels.ts, the closed list of company
// industry labels discovery can search (LIF-1694). The provider publishes no
// list and returns zero people, not an error, for a label it does not know,
// so a label is accepted only with evidence that it matches people.
//
// probe (the decided method): one free People Search count per candidate, the
// endpoint Jobs discovery uses, filtered by that label alone with per_page 1.
// A label is accepted when the count is above zero. It never calls enrichment
// or reveal endpoints, sends at most two requests per second and stops on 429.
// It needs a key whose plan includes API People Search:
//   APOLLO_API_KEY=<key> node scripts/industry-labels.mjs probe --candidates <file.json>
// Candidates are the committed labels plus each --candidates file: a JSON array
// of strings, or of rows with an `industry` or `v` field. Values stored in
// production make good candidates (read-only SQL):
//   select distinct industry from public.leads where industry is not null
//   union select distinct unnest(organization_industries) from public.icp_configs;
//
// observed (interim evidence until a probe runs): the employer industries the
// provider assigned to people discovery found and enriched, from
//   select industry, count(*) n from public.leads
//   where discovery_run_id is not null and apollo_id is not null
//     and industry is not null and created_at >= '2026-07-01' group by 1;
//   node scripts/industry-labels.mjs observed --leads <rows.json>
// Only exact lowercase values are kept: production discovery shows the filter
// matches the exact label ("Accounting" and "Automotive" found nobody where
// "automotive" did).
import { readFileSync, writeFileSync } from "node:fs";

const target = new URL("../src/generated/industry-labels.ts", import.meta.url);
const [mode, ...rest] = process.argv.slice(2);
const options = (name) => rest.flatMap((value, index) => (rest[index - 1] === name ? [value] : []));
const today = new Date().toISOString().slice(0, 10);
const current = () =>
  [...readFileSync(target, "utf8").matchAll(/^ {2}("(?:[^"\\]|\\.)*"),/gm)].map(([, label]) => JSON.parse(label));
const valuesOf = (file) =>
  JSON.parse(readFileSync(file, "utf8")).map((row) => (typeof row === "string" ? row : row.industry ?? row.v));

function write(header, counted, unit) {
  const labels = [...counted].filter(([label]) => typeof label === "string" && label.trim() === label && label)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  writeFileSync(target, `${header.map((line) => `// ${line}`.trimEnd()).join("\n")}
export const INDUSTRY_LABELS = [
${labels.map(([label, count]) => `  ${JSON.stringify(label)}, // ${count} ${unit}`).join("\n")}
] as const;
`);
  console.log(`Wrote ${labels.length} labels to src/generated/industry-labels.ts.`);
}

const rerun = [
  "Rerun the free count probe with a key whose plan includes API People Search:",
  "  APOLLO_API_KEY=<key> node scripts/industry-labels.mjs probe --candidates <file.json>",
  "The script header documents the method and the candidate queries.",
];

if (mode === "observed") {
  const [file] = options("--leads");
  if (!file) throw new Error("Usage: node scripts/industry-labels.mjs observed --leads <rows.json>");
  const counts = new Map();
  for (const row of JSON.parse(readFileSync(file, "utf8"))) {
    const label = row.industry;
    if (typeof label === "string" && label && label === label.toLowerCase() && label.trim() === label)
      counts.set(label, (counts.get(label) ?? 0) + Number(row.n));
  }
  write([
    "Searchable company industry labels: the only values company.industries accepts.",
    `Generated by scripts/industry-labels.mjs on ${today}; do not edit by hand (LIF-1694).`,
    "Evidence: observed. Each label is an employer industry the provider assigned to",
    "people discovery found and enriched since 2026-07-01; the count is those people.",
    "The count probe has not run yet: the key available on 2026-10-28 is on a plan",
    "without API People Search.",
    ...rerun,
  ], counts, "discovered leads");
} else if (mode === "probe") {
  const key = process.env.APOLLO_API_KEY?.trim();
  if (!key) throw new Error("Set APOLLO_API_KEY in the environment; it is never printed or written.");
  const candidates = [...new Set([...current(), ...options("--candidates").flatMap(valuesOf)]
    .filter((value) => typeof value === "string" && value.trim() === value && value))];
  const counts = new Map();
  const rejected = [];
  for (const label of candidates) {
    const response = await fetch("https://api.apollo.io/api/v1/mixed_people/api_search", {
      method: "POST",
      headers: { "content-type": "application/json", "cache-control": "no-cache", "x-api-key": key },
      body: JSON.stringify({ organization_industries: [label], per_page: 1, page: 1 }),
    });
    if (response.status === 429) throw new Error(`Rate limited at "${label}"; nothing was written.`);
    if (!response.ok) throw new Error(`People Search returned ${response.status} at "${label}"; nothing was written.`);
    const body = await response.json();
    const total = Number(body.total_entries ?? body.pagination?.total_entries ?? 0);
    if (total > 0) counts.set(label, total);
    else rejected.push(label);
    await new Promise((resolve) => setTimeout(resolve, 550));
  }
  write([
    "Searchable company industry labels: the only values company.industries accepts.",
    `Generated by scripts/industry-labels.mjs on ${today}; do not edit by hand (LIF-1694).`,
    `Evidence: probe on ${today}. Each label alone returned more than zero people in a`,
    "free People Search count (per_page 1); the count is that total.",
    `${candidates.length} candidates probed, ${counts.size} accepted.`,
    ...rerun,
  ], counts, "people");
  console.log(`Rejected (zero people): ${JSON.stringify(rejected)}`);
} else {
  throw new Error("Usage: node scripts/industry-labels.mjs <probe|observed> ...");
}
